import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { test } from "node:test";
import { DELIVERY_IS, capState, factsFromState, factsOf, groove, paidIn, pct, ratio, sweeps } from "../src/lib/vault.js";
import type { Acquisition, ListingDetail } from "../src/api/types.js";

/**
 * docs/phase14.md §8. The vault's own page: every figure it prints, read off the two sources that reach it, and the four
 * rows Nosh's collection page has that Etch either shapes differently or cannot print at all.
 *
 * Both fixture sets are used on purpose and they disagree on purpose. The **recording** was taken off the staging indexer
 * on 2026-09-21 and predates every field §8.4 added, so it is what a live deployment looks like today and it is where
 * "absent is not zero" is actually exercised. The **synthetic** set is regenerated by the indexer in CI and does carry
 * them, so it is where the arithmetic is checked.
 */
const here = (p: string) => new URL(p, import.meta.url);
const raw = <T,>(set: "demo" | "synthetic", f: string): T => JSON.parse(readFileSync(here(`../public/fixtures/${set}/${f}`), "utf8")) as T;
const listing = (set: "demo" | "synthetic", id: number) => raw<ListingDetail>(set, `listing-${id}.json`);
const page = readFileSync(here("../src/components/vaultpage.tsx"), "utf8");
const css = readFileSync(here("../src/styles/etch.css"), "utf8");
const vaults = readFileSync(here("../src/pages/Vaults.tsx"), "utf8");
const NOW = 1_800_001_500;

test("the budget is not the balance, and on the recorded vault the difference is the bond", () => {
  const l = listing("demo", 0), f = factsOf(l, NOW);
  assert.equal(f.unknown, null);
  assert.equal(f.budget, BigInt(l.live!.spendableWei!), "what a declaration can reach");
  assert.equal(f.balance, BigInt(l.live!.balanceWei!));
  assert.ok(f.balance! > f.budget! * 19n, `the balance is twenty times the budget on this vault: ${f.balance} against ${f.budget}`);
  assert.equal(f.balance! - f.budget!, f.bond!, "and all of the difference is the purchaser's bond, which is not the vault's to spend");
});

test("unattributed is what Etch has instead of donations, and it is zero because there is no way to donate", () => {
  for (const id of [0, 1]) {
    const f = factsOf(listing("demo", id), NOW);
    assert.equal(f.unattributed, 0n, `vault ${id}: every wei is a coin's or the purchaser's bond`);
  }
  // and it is a subtraction, so a source missing one of its terms has no figure rather than a comforting zero
  const partial = { ...listing("demo", 0), live: { ...listing("demo", 0).live!, waitingWei: null } };
  assert.equal(factsOf(partial, NOW).unattributed, null);
});

test("the recording predates the totals, and each one is absent rather than zero", () => {
  const f = factsOf(listing("demo", 0), NOW);
  assert.deepEqual([f.spent, f.released, f.returned], [null, null, null], "released, returned and spent are not reported by this source");
  assert.deepEqual([f.bought, f.held, f.delivered], [null, null, null], "nor the holdings");
  assert.equal(f.cap!.postedAt, null, "nor when the cap was posted — though the cap itself is there");
  assert.notEqual(f.fedIn, null, "what WAS always served stays served");
  assert.equal(f.fedIn, BigInt(listing("demo", 0).depositedWei));
});

test("a collection's vault: a count bought, a count held, and what its purchases cost", () => {
  const f = factsOf(listing("synthetic", 0), NOW);
  assert.deepEqual([f.released, f.returned, f.spent, f.writtenOff], [80n, 5n, 55n, 5n]);
  assert.deepEqual(f.bought, { kind: "inscriptions", items: 5 });
  assert.deepEqual(f.held, { kind: "inscriptions", items: 4 }, "five receipted, one delivered");
  assert.equal(f.delivered, 1);
  assert.equal(f.paidOut, null, "a collection has no units to pay out");
});

test("a rune's vault is measured, not counted: 'swept N' is not a sentence about something fungible", () => {
  const f = factsOf(listing("synthetic", 1), NOW);
  assert.deepEqual(f.bought, { kind: "rune", units: 900n, receipts: 1 });
  assert.deepEqual(f.held, { kind: "rune", units: 600n, receipts: 1 }, "900 in, 300 paid out on a recorded claim");
  assert.equal(f.paidOut, 300n);
  assert.deepEqual([f.bought!.kind === "rune" && f.bought.units, f.held!.kind === "rune" && f.held.units], [900n, 600n]);
});

test("the indexed totals survive a live block that could not be read", () => {
  const f = factsOf(listing("synthetic", 0), NOW);
  assert.match(f.unknown!, /were not available/, "no node answered, and the panel says so once");
  assert.deepEqual([f.budget, f.balance, f.bond], [null, null, null], "everything that needed the chain is unknown");
  assert.deepEqual([f.spent, f.bought], [55n, { kind: "inscriptions", items: 5 }], "everything folded from events is still there");
  assert.equal(f.buysNow, null, "and a ratio with an unknown numerator is not a number");
});

test("a cap is live or expired, and the page is told from which end of its hour", () => {
  const l = listing("synthetic", 0);
  const live = capState(l, NOW)!;
  assert.deepEqual([live.wei, live.live, live.postedAt], [60n, true, 1_800_000_492]);
  assert.ok(live.postedAt! < live.expiry, "posted at one end, expiring at the other");
  assert.equal(capState(l, live.expiry + 1)!.live, false, "this browser's own clock is enough to expire it");
  assert.equal(capState({ ...l, capExpired: true }, NOW)!.live, false, "and so is the indexer's own comparison");
  assert.equal(capState({ ...l, capWei: null }, NOW), null, "no cap is null, not a cap of zero");
  assert.equal(capState({ ...l, capWei: "0" }, NOW), null);
  assert.equal(capState(l, NOW, 5_000)!.expiry, l.capExpiry! + 5_000, "a recorded demo's times are moved, both ends together");
  assert.equal(capState(l, NOW, 5_000)!.postedAt, 1_800_005_492);
});

test("what the budget buys at the cap, and what a ratio does when it has no denominator", () => {
  assert.equal(ratio(30n, 60n), 0.5);
  assert.equal(ratio(0n, 60n), 0);
  assert.equal(ratio(600n, 60n), 10, "a vault that can already afford ten of them is not clamped to one");
  assert.equal(ratio(30n, 0n), null, "no cap, no ratio");
  assert.equal(ratio(null, 60n), null);
  assert.deepEqual([groove(10), groove(0.5), groove(null), groove(-1), groove(Number.NaN)], [1, 0.5, 0, 0, 0], "the bar clamps; the figure does not");
});

test("the coins feeding a vault, largest first, with shares of the same response's own total", () => {
  const l = listing("demo", 0);
  const rows = paidIn(l);
  assert.equal(rows.length, l.coinsList.length);
  assert.deepEqual(rows.map((r) => r.wei), [...rows.map((r) => r.wei)].sort((a, b) => (b > a ? 1 : b < a ? -1 : 0)), "largest first");
  const total = rows.reduce((t, r) => t + r.share!, 0);
  assert.ok(Math.abs(total - 1) < 1e-4, `shares are of the whole and add to it: ${total}`);
  assert.equal(paidIn({ coinsList: l.coinsList, depositedWei: "0" })[0].share, null, "a vault nothing has been fed has no shares rather than shares of zero");
  assert.deepEqual([pct(0.352), pct(0.0285), pct(0), pct(null), pct(Number.NaN)], ["35.2%", "2.85%", "0%", null, null]);
});

test("a receipt carries its purchase's cost where the source has one, and says nothing where it does not", () => {
  const rows = sweeps(listing("synthetic", 0).acquisitionsRecent);
  assert.deepEqual(rows.map((r) => r.acquisitionId), [4, 3, 2, 1, 0], "newest first");
  assert.ok(rows.every((r) => r.purchaseSpent === 55n && r.purchaseItems === 5),
    "one purchase, five inscriptions: the page prints the purchase's figure and says how many shared it, and divides neither by the other");
  const old = sweeps(listing("demo", 0).acquisitionsRecent);
  assert.ok(old.every((r) => r.purchaseSpent === null && r.purchaseItems === null), "the recording has neither, and gets null for both");
  assert.ok(old.every((r) => r.satsPaid >= 0n && r.coin.startsWith("0x")));
});

test("every delivery state has words, because 'draw-pinned' is a database value and not a thing to show a reader", () => {
  const states: Acquisition["delivery"]["state"][] = ["undecided", "held", "never-delivered", "draw-open", "draw-pinned", "draw-resolved",
    "won", "delivered", "voided", "cancelled", "distribution-open", "distribution-rolled"];
  for (const s of states) assert.ok(DELIVERY_IS[s] && !DELIVERY_IS[s].includes("-"), `${s} -> ${DELIVERY_IS[s]}`);
  assert.equal(Object.keys(DELIVERY_IS).length, states.length, "and no state is missing one");
  const seen = new Set(sweeps(listing("demo", 0).acquisitionsRecent).map((r) => r.state));
  for (const s of seen) assert.ok(DELIVERY_IS[s], `the recording reaches ${s}, which therefore has to have words`);
});

